/// 简体 → 繁体。
String toTraditional(String input) {
  if (input.isEmpty) return input;
  final sb = StringBuffer();
  var i = 0;
  while (i < input.length) {
    var matched = false;
    for (var len = 4; len >= 2; len--) {
      if (i + len <= input.length) {
        final key = input.substring(i, i + len);
        final v = _s2tPhrases[key];
        if (v != null) {
          sb.write(v);
          i += len;
          matched = true;
          break;
        }
      }
    }
    if (matched) continue;
    final ch = input[i];
    sb.write(_s2t[ch] ?? ch);
    i++;
  }
  return sb.toString();
}

/// 繁体 → 简体。
String toSimplified(String input) {
