}

/// 中文标点禁则优化：让省略号 / 破折号这类「成对字符」不跨行折断。
///
/// 实现：在两个连续标点之间插入 Word Joiner（U+2060，零宽、不可见、禁止换行）。
/// 引擎（Skia UAX#14）本身已禁止 `。！？` 出现在行首、`「《` 出现在行尾，
/// 这里补齐它不覆盖的 `……` / `——` 中间断行问题。
String optimizePunctuation(String input) {
  if (input.isEmpty) return input;
  var s = input;
  // 省略号（U+2026 U+2026）
  s = s.replaceAll('\u2026\u2026', '\u2026\u2060\u2026');
  // 破折号（U+2014 U+2014）
  s = s.replaceAll('\u2014\u2014', '\u2014\u2060\u2014');
  return s;
}
